"""Classify the vote retriever's file hit@5 misses on the test half and write docs/MISSES.md."""

import argparse
from collections import Counter
from pathlib import Path

import numpy as np

from recallbench.data import load
from recallbench.files import MAIN_N
from recallbench.retrieve import Corpus
from recallbench.split import date_split
from recallbench.stats import SEED
from recallbench.vote import VOTE, vote_files

HUGE = 10
SAMPLE = 20
CATEGORIES = (
    "new to the history: no earlier session or fix names a gold file",
    "only in the fix history, ranked below 5",
    "huge-session noise: a top voting session names more than 10 files",
    "named by a voting session, outranked",
    "in earlier sessions, but none of the top voting sessions",
)


def classify(corpus: Corpus, q: int) -> dict | None:
    """None for a hit, otherwise the miss's category and the best rank of a gold file."""
    gold = set(corpus.tasks[q].gold_files)
    ranked = [corpus.sessions[i] for i in corpus.rank("hybrid", q)]
    prior = corpus.past_fix_files(q)
    files = vote_files(ranked, prior)
    if gold & set(files[:MAIN_N]):
        return None
    in_sessions = any(gold & set(session.pointers) for session in ranked)
    if not in_sessions and not gold & set(prior):
        category = CATEGORIES[0]
    elif not in_sessions:
        category = CATEGORIES[1]
    elif any(len(session.pointers) > HUGE for session in ranked[: VOTE.depth]):
        category = CATEGORIES[2]
    elif any(gold & set(session.pointers) for session in ranked[: VOTE.depth]):
        category = CATEGORIES[3]
    else:
        category = CATEGORIES[4]
    ranks = [files.index(path) + 1 for path in gold if path in files]
    return {"category": category, "best_rank": min(ranks) if ranks else None}


def _example(corpus: Corpus, q: int, miss: dict) -> str:
    task = corpus.tasks[q]
    gold = ", ".join(f"`{path}`" for path in task.gold_files)
    rank = miss["best_rank"] or "absent"
    return f"| {task.instance_id} | {gold} | {rank} | {miss['category'].split(':')[0]} |"


def render(tasks, sessions) -> str:
    corpus = Corpus(tasks, sessions)
    _, test = date_split(tasks, corpus.queries())
    misses = {q: miss for q in test if (miss := classify(corpus, q))}
    counts = Counter(miss["category"] for miss in misses.values())
    non_python = sum(all(not path.endswith(".py") for path in tasks[q].gold_files) for q in misses)
    rng = np.random.default_rng(SEED)
    sample = sorted(rng.choice(sorted(misses), size=min(SAMPLE, len(misses)), replace=False).tolist())
    lines = [
        "# Test-half misses of `vote_prior`",
        "",
        "Generated by `tools/misses.py`. Do not edit by hand. A miss is a test-half query where none of the first "
        f"{MAIN_N} files of `vote_prior` is a gold file. Categories are checked in the order listed.",
        "",
        f"{len(misses)} misses out of {len(test)} test queries.",
        "",
        "| Category | Misses |",
        "|---|---|",
        *(f"| {category} | {counts[category]} |" for category in CATEGORIES),
        "",
        f"Misses whose gold files are all non-Python (docs, changelogs, config): {non_python}.",
        "",
        f"A seeded sample of {len(sample)} misses. Best rank is the best rank of a gold file in the full `vote_prior` "
        f"list, which holds only files named by the top {VOTE.depth} sessions or by earlier fixes, so a gold file "
        "outside both is absent.",
        "",
        "| Task | Gold files | Best rank | Category |",
        "|---|---|---|---|",
        *(_example(corpus, q, misses[q]) for q in sample),
    ]
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=Path("docs/MISSES.md"))
    args = parser.parse_args(argv)
    args.out.write_text(render(*load()), encoding="utf-8")


if __name__ == "__main__":
    main()
